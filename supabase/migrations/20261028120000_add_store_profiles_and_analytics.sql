-- Profil toko publik + analitik kunjungan produk.
-- Jalankan migrasi ini sebelum memakai halaman /toko/[id],
-- /kelolatoko/profil, dan ringkasan analitik di dashboard toko.

ALTER TABLE public.stores
  ADD COLUMN IF NOT EXISTS deskripsi text,
  ADD COLUMN IF NOT EXISTS foto_profil text,
  ADD COLUMN IF NOT EXISTS banner text,
  ADD COLUMN IF NOT EXISTS lokasi text;

CREATE TABLE IF NOT EXISTS public.product_views (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  id_produk uuid NOT NULL REFERENCES public.products(id) ON DELETE CASCADE,
  id_toko uuid NOT NULL REFERENCES public.stores(id) ON DELETE CASCADE,
  sumber text NOT NULL DEFAULT 'detail',
  created_at timestamptz NOT NULL DEFAULT now()
);

CREATE INDEX IF NOT EXISTS product_views_toko_created_idx
  ON public.product_views (id_toko, created_at DESC);

CREATE INDEX IF NOT EXISTS product_views_produk_created_idx
  ON public.product_views (id_produk, created_at DESC);

ALTER TABLE public.product_views ENABLE ROW LEVEL SECURITY;

